namespace GuildSimulator.Core;

/// <summary>
/// 実装とマスタデータを残したまま、機能そのものを丸ごと止めるためのスイッチ。
/// 「作り直す」のではなく「切っておく」ためのものなので、フラグを戻すだけで復活する。
/// </summary>
public static class GameFeatures
{
    /// <summary>
    /// 遺物システムの有効/無効。<b>現在は凍結中（false）</b>。
    ///
    /// 永久バフの入手経路を施設に一本化し、遺物×施設の二重管理をなくすために止めている。
    /// 凍結中は次のようになる（コードもマスタデータもそのまま残る）。
    ///
    /// <list type="bullet">
    ///   <item>遺物の効果はすべて無効（加算0・倍率1.0）。所持済みの遺物も効かない</item>
    ///   <item>宝箱・ボスドロップ・敵ドロップから遺物が出ない（他の中身の抽選には影響しない）</item>
    ///   <item>メインメニューから「遺物一覧」が消え、ヘルプからも遺物の記述が消える</item>
    ///   <item>セーブデータの <c>relicIds</c> は読み書きし続けるので、所持記録は失われない</item>
    /// </list>
    ///
    /// 復活させるときはこの値を <c>true</c> に戻すだけでよい。
    /// 凍結中に進めたセーブデータでも、記録済みの遺物がそのまま効き始める。
    /// </summary>
    public static bool RelicsEnabled { get; set; } = false;
}
